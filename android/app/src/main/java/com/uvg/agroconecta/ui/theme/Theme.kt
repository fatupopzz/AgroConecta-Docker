@Composable
fun AgroConectaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    // Sin color dinámico: en teléfonos con Material You el verde de marca se
    // perdería y con él la referencia visual de "esto es AgroConecta".
    val colorScheme = if (darkTheme) AgroConectaDarkColors else AgroConectaLightColors
    val agroColors = if (darkTheme) DarkAgroColors else LightAgroColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // La barra de estado continúa la barra superior de cada pantalla.
            window.statusBarColor = agroColors.topBarContainer.toArgb()
            window.navigationBarColor = colorScheme.surfaceContainer.toArgb()
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = false
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalAgroColors provides agroColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AgroConectaTypography,
            shapes = AgroConectaShapes,
            content = content
        )
    }
}
